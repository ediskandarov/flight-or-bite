"""Generate reports/jev_templates.md and the request-body section of docs/jev_api_notes.md from
configs/jev_prompts/*.yaml, so that the texts shown to the author are verbatim."""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from flight_or_bite.arbiters.jev_arbiter import MODES, load_prompt, prompt_hash
from flight_or_bite.arbiters.jev_client import MODEL, build_payload
from flight_or_bite.policy_table.table import load_grid
from flight_or_bite.types import Observation

OBS = Observation(sugar=0.6, bitter=0.05, looming=0.5, hunger=0.5)
env = yaml.safe_load(Path("configs/env.yaml").read_text())
grid = load_grid()


def body(mode: str) -> str:
    p = load_prompt(mode)
    raw = build_payload(p.state(OBS), {"action": p.question()}, MODEL)
    return json.dumps(json.loads(raw), ensure_ascii=False, indent=2)


def unique_requests(mode: str) -> int:
    p = load_prompt(mode)
    return len({p.state_key(grid.observation(i)) for i in grid.points()})


L = [
    "# Шаблоны запросов Jev — версия v1",
    "",
    "Сгенерировано `scripts/jev_templates_report.py` из `configs/jev_prompts/*.yaml`; тексты дословные. **v1 утверждена автором спецификации 2026-09-20 с правками; на `dev` не настраивалась.** Хэши файлов входят в `PREREG.md`.",
    "",
    f"Модель: `{MODEL}` (ответ не из этого семейства прерывает прогон). Эндпоинт: `POST https://openrouter.ai/api/alpha/decisions`, заголовок `X-OpenRouter-Cache: false`. Один вопрос типа `choice` с идентификатором `action`. Действие арбитра — поле `choice` ответа (D27); вероятности — поле `probabilities`.",
    "",
    "## Дизайн 2 × 2",
    "",
    "| | наблюдение числами | наблюдение уровнями |",
    "|---|---|---|",
    "| **без пакета правил** | `naive` | `bucketed` |",
    "| **с пакетом правил** | `informed` | `informed_bucketed` |",
    "",
    "- **Фактор «правила» — пакет:** текст правил среды **и** описания вариантов в `criteria`; появляются и исчезают вместе, по отдельности не варьируются (D46).",
    "- Правила идут в поле `instructions` **перед вопросом**; `state` содержит только наблюдение (D46).",
    "- Вопрос одинаков во всех четырёх режимах: «Which action should the agent take on this trial?»",
    "- Числа наблюдения округляются до 2 знаков.",
    "- Уровни (5 равных по ширине): ровно 0 → `none`; (0, 0.2) → `very low`; [0.2, 0.4) → `low`; [0.4, 0.6) → `medium`; [0.6, 0.8) → `high`; [0.8, 1] → `very high`.",
    f"- Числа в правилах — из `configs/env.yaml`: `p_food` {env['p_food']}, `eat_gain` {env['eat_gain']:g}, `escape_cost` {env['escape_cost']:g}, `toxic_cost` {env['toxic_cost']:g}, `p_toxic` {env['p_toxic']}, `p_threat` {env['p_threat']}, `p_death_eat` {env['p_death_eat']}, `p_death_idle` {env['p_death_idle']}; совпадение проверяется тестом.",
    f"- В бакетных режимах запрашиваются только уникальные комбинации уровней (D47): на сетке B ({len(grid.points())} точек) это {unique_requests('bucketed')} разных запросов; остальные точки получают копии ответов с пометкой `cache_hit` и в статистику латентности не входят.",
    "",
]
for mode in MODES:
    p = load_prompt(mode)
    L += [
        f"## `{mode}`",
        "",
        f"Файл `configs/jev_prompts/{mode}.yaml`, версия {p.version}, SHA-256 `{prompt_hash(mode)}`.",
        "",
        "**criteria:**",
        "",
    ]
    L += [f"- `{k}`: {('«' + v + '»') if v else '`null` (без описания)'}" for k, v in p.criteria.items()]
    L += [
        "",
        "**instructions** (целиком, как уходит в запрос):",
        "",
        "> " + p.full_instructions.replace("\n\n", "\n>\n> "),
        "",
        f"Тело HTTP-запроса для наблюдения sugar {OBS.sugar}, bitter {OBS.bitter}, looming {OBS.looming}, hunger {OBS.hunger}:",
        "",
        "```json",
        body(mode),
        "```",
        "",
    ]
a, b = load_prompt("informed").rules, load_prompt("informed_bucketed").rules
tail = "`sugar` is the amount of food present"
L += [
    "## Чем `informed_bucketed` отличается от `informed`",
    "",
    "Только фразой, описывающей наблюдение; остальной текст правил и `criteria` совпадают посимвольно (проверяется тестом).",
    "",
    "- `informed`: «" + a[: a.index(tail)].strip().split(". ", 1)[1] + "»",
    "- `informed_bucketed`: «" + b[: b.index(tail)].strip().split(". ", 1)[1] + "»",
    "",
]
Path("reports/jev_templates.md").write_text("\n".join(L))

notes = Path("docs/jev_api_notes.md")
s = notes.read_text()
marker = "## 12. Full request body for each state mode (templates v1)"
if marker in s:
    s = (
        s[: s.index(marker)].rstrip() + "\n\n" + s[s.index("## Not documented") :]
        if s.index("## Not documented") > s.index(marker)
        else s[: s.index(marker)].rstrip() + "\n"
    )
section = [
    marker,
    "",
    "Generated by `scripts/jev_templates_report.py` from `configs/jev_prompts/` for the observation",
    f"sugar {OBS.sugar}, bitter {OBS.bitter}, looming {OBS.looming}, hunger {OBS.hunger}. Wire format is compact JSON with sorted keys;",
    "it is pretty-printed here. In the informed modes the rules precede the question inside",
    "`instructions`, and `state` carries the observation only (decision D46).",
    "",
]
for mode in MODES:
    section += [f"### `{mode}`", "", "```json", body(mode), "```", ""]
i = s.index("## Not documented")
notes.write_text(s[:i] + "\n".join(section) + "\n" + s[i:])
print(
    "wrote reports/jev_templates.md and docs/jev_api_notes.md §12;",
    {m: unique_requests(m) for m in MODES},
)
