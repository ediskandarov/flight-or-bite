"""Generate reports/jev_templates.md and the request-body section of docs/jev_api_notes.md from
configs/jev_prompts/*.yaml, so that the texts shown to the author are verbatim."""

from __future__ import annotations

import json
from pathlib import Path

import yaml

from flight_or_bite.arbiters.jev_arbiter import MODES, load_prompt, prompt_hash
from flight_or_bite.arbiters.jev_client import MODEL, build_payload
from flight_or_bite.policy_table.table import load_grid
from flight_or_bite.types import Observation

OBS = Observation(sugar=0.6, bitter=0.05, looming=0.5, hunger=0.5)
env = yaml.safe_load(Path("configs/env.yaml").read_text())
grid = load_grid()


def body(mode: str) -> str:
    p = load_prompt(mode)
    raw = build_payload(p.state(OBS), {"action": p.question()}, MODEL)
    return json.dumps(json.loads(raw), ensure_ascii=False, indent=2)


def unique_requests(mode: str) -> int:
    p = load_prompt(mode)
    return len({p.state_key(grid.observation(i)) for i in grid.points()})


L = [
    "# Jev request templates — version v1",
    "",
    "Generated by `scripts/jev_templates_report.py` from `configs/jev_prompts/*.yaml`; template text is verbatim. **v1 was approved with amendments by the specification author on 2026-09-20; it was not tuned on `dev`.** File hashes are included in `PREREG.md`.",
    "",
    f"Model: `{MODEL}` (a response outside this family aborts the run). Endpoint: `POST https://openrouter.ai/api/alpha/decisions`, header `X-OpenRouter-Cache: false`. One `choice` question with ID `action`. The arbiter action is the response's `choice` field (D27); probabilities come from `probabilities`.",
    "",
    "## 2 × 2 design",
    "",
    "| | Numeric observation | Bucketed observation |",
    "|---|---|---|",
    "| **Without rules package** | `naive` | `bucketed` |",
    "| **With rules package** | `informed` | `informed_bucketed` |",
    "",
    "- **The rules factor is a package:** environment rules **and** option descriptions in `criteria` appear and disappear together; they are not varied independently (D46).",
    "- Rules are placed in `instructions` **before the question**; `state` contains only the observation (D46).",
    "- All four modes use the same question: “Which action should the agent take on this trial?”",
    "- Observation values are rounded to 2 decimal places.",
    "- Levels (5 equal-width bins): exactly 0 → `none`; (0, 0.2) → `very low`; [0.2, 0.4) → `low`; [0.4, 0.6) → `medium`; [0.6, 0.8) → `high`; [0.8, 1] → `very high`.",
    f"- Rule values come from `configs/env.yaml`: `p_food` {env['p_food']}, `eat_gain` {env['eat_gain']:g}, `escape_cost` {env['escape_cost']:g}, `toxic_cost` {env['toxic_cost']:g}, `p_toxic` {env['p_toxic']}, `p_threat` {env['p_threat']}, `p_death_eat` {env['p_death_eat']}, `p_death_idle` {env['p_death_idle']}; consistency is tested.",
    f"- Bucketed modes query only unique level combinations (D47): grid B ({len(grid.points())} points) has {unique_requests('bucketed')} distinct requests; other points receive copied responses marked `cache_hit`, excluded from latency statistics.",
    "",
]
for mode in MODES:
    p = load_prompt(mode)
    L += [
        f"## `{mode}`",
        "",
        f"File `configs/jev_prompts/{mode}.yaml`, version {p.version}, SHA-256 `{prompt_hash(mode)}`.",
        "",
        "**criteria:**",
        "",
    ]
    L += [f"- `{k}`: {('“' + v + '”') if v else '`null` (no description)'}" for k, v in p.criteria.items()]
    L += [
        "",
        "**instructions** (complete text, exactly as sent):",
        "",
        "> " + p.full_instructions.replace("\n\n", "\n>\n> "),
        "",
        f"HTTP request body for observation sugar {OBS.sugar}, bitter {OBS.bitter}, looming {OBS.looming}, hunger {OBS.hunger}:",
        "",
        "```json",
        body(mode),
        "```",
        "",
    ]
a, b = load_prompt("informed").rules, load_prompt("informed_bucketed").rules
tail = "`sugar` is the amount of food present"
L += [
    "## How `informed_bucketed` differs from `informed`",
    "",
    "Only the sentence describing the observation differs; the rest of the rules and `criteria` are character-for-character identical (verified by a test).",
    "",
    "- `informed`: «" + a[: a.index(tail)].strip().split(". ", 1)[1] + "»",
    "- `informed_bucketed`: «" + b[: b.index(tail)].strip().split(". ", 1)[1] + "»",
    "",
]
Path("reports/jev_templates.md").write_text("\n".join(L))

notes = Path("docs/jev_api_notes.md")
s = notes.read_text()
marker = "## 12. Full request body for each state mode (templates v1)"
if marker in s:
    s = (
        s[: s.index(marker)].rstrip() + "\n\n" + s[s.index("## Not documented") :]
        if s.index("## Not documented") > s.index(marker)
        else s[: s.index(marker)].rstrip() + "\n"
    )
section = [
    marker,
    "",
    "Generated by `scripts/jev_templates_report.py` from `configs/jev_prompts/` for the observation",
    f"sugar {OBS.sugar}, bitter {OBS.bitter}, looming {OBS.looming}, hunger {OBS.hunger}. Wire format is compact JSON with sorted keys;",
    "it is pretty-printed here. In the informed modes the rules precede the question inside",
    "`instructions`, and `state` carries the observation only (decision D46).",
    "",
]
for mode in MODES:
    section += [f"### `{mode}`", "", "```json", body(mode), "```", ""]
i = s.index("## Not documented")
notes.write_text(s[:i] + "\n".join(section) + "\n" + s[i:])
print(
    "wrote reports/jev_templates.md and docs/jev_api_notes.md §12;",
    {m: unique_requests(m) for m in MODES},
)
